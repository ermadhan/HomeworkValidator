import React, { useState } from 'react';
import { X, Sparkles, HelpCircle, CheckCircle, ChevronDown, ChevronUp, Copy, Check } from 'lucide-react';
import { PracticeItem } from '../types/homework';

interface PracticeModalProps {
  isOpen: boolean;
  onClose: () => void;
  practiceItems: PracticeItem[];
  isLoading: boolean;
}

export const PracticeModal: React.FC<PracticeModalProps> = ({
  isOpen,
  onClose,
  practiceItems,
  isLoading,
}) => {
  const [openSolutions, setOpenSolutions] = useState<Record<number, boolean>>({});
  const [copied, setCopied] = useState(false);

  if (!isOpen) return null;

  const toggleSolution = (index: number) => {
    setOpenSolutions((prev) => ({
      ...prev,
      [index]: !prev[index],
    }));
  };

  const copyPracticeSheet = () => {
    const text = practiceItems
      .map(
        (item, idx) =>
          `Practice Problem ${idx + 1} (${item.concept}):\n${item.question}\n\nHint: ${item.hints}\n\nSolution: ${item.solution}\n-------------------`
      )
      .join('\n\n');

    navigator.clipboard.writeText(text);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  return (
    <div className="fixed inset-0 z-50 bg-slate-900/80 backdrop-blur-xs flex items-center justify-center p-3 sm:p-6">
      <div className="bg-white rounded-2xl w-full max-w-2xl max-h-[90vh] flex flex-col shadow-2xl overflow-hidden">
        {/* Header */}
        <div className="px-5 py-4 border-b border-slate-200 flex items-center justify-between bg-gradient-to-r from-indigo-50 to-purple-50">
          <div className="flex items-center space-x-2">
            <span className="p-2 rounded-xl bg-indigo-600 text-white shadow-xs">
              <Sparkles className="w-5 h-5" />
            </span>
            <div>
              <h3 className="font-bold text-slate-900 text-base">
                Tailored Remedial Practice Problems
              </h3>
              <p className="text-xs text-slate-500">
                Generated by Gemini to help the student master the concepts they missed
              </p>
            </div>
          </div>
          <button
            onClick={onClose}
            className="p-1.5 rounded-lg text-slate-400 hover:text-slate-700 hover:bg-white/80"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Content */}
        <div className="p-6 overflow-y-auto flex-1 space-y-4">
          {isLoading ? (
            <div className="py-12 flex flex-col items-center justify-center text-center">
              <div className="w-10 h-10 border-3 border-indigo-200 border-t-indigo-600 rounded-full animate-spin mb-3" />
              <p className="text-sm font-semibold text-slate-700">Designing targeted practice problems...</p>
              <p className="text-xs text-slate-400 mt-1">Analyzing missed question patterns and error mechanics</p>
            </div>
          ) : practiceItems.length === 0 ? (
            <div className="text-center py-8 text-slate-500 text-sm">
              No practice exercises found or student scored 100%!
            </div>
          ) : (
            practiceItems.map((item, index) => {
              const isSolutionOpen = openSolutions[index];
              return (
                <div
                  key={index}
                  className="bg-slate-50 border border-slate-200 rounded-xl p-4 transition-all hover:border-slate-300"
                >
                  <div className="flex items-center justify-between mb-2">
                    <span className="text-xs font-bold uppercase tracking-wider px-2 py-0.5 rounded-md bg-indigo-100 text-indigo-800">
                      Problem {index + 1}: {item.concept}
                    </span>
                  </div>

                  <p className="text-sm font-medium text-slate-800 mb-3 whitespace-pre-line">
                    {item.question}
                  </p>

                  {/* Hint banner */}
                  <div className="bg-amber-50/70 border border-amber-200/60 rounded-lg p-2.5 mb-3 flex items-start space-x-2 text-xs text-amber-900">
                    <HelpCircle className="w-4 h-4 text-amber-600 shrink-0 mt-0.5" />
                    <div>
                      <span className="font-semibold">Hint: </span>
                      {item.hints}
                    </div>
                  </div>

                  {/* Solution toggle */}
                  <div className="border-t border-slate-200/80 pt-2">
                    <button
                      onClick={() => toggleSolution(index)}
                      className="text-xs font-semibold text-indigo-600 hover:text-indigo-800 flex items-center"
                    >
                      {isSolutionOpen ? (
                        <>
                          <ChevronUp className="w-3.5 h-3.5 mr-1" />
                          Hide Step-by-Step Solution
                        </>
                      ) : (
                        <>
                          <ChevronDown className="w-3.5 h-3.5 mr-1" />
                          Show Step-by-Step Solution
                        </>
                      )}
                    </button>

                    {isSolutionOpen && (
                      <div className="mt-2 p-3 bg-emerald-50/80 border border-emerald-200 rounded-lg text-xs text-emerald-900 whitespace-pre-line font-mono">
                        <div className="font-bold flex items-center mb-1 text-emerald-800 font-sans">
                          <CheckCircle className="w-3.5 h-3.5 mr-1 text-emerald-600" />
                          Complete Solution:
                        </div>
                        {item.solution}
                      </div>
                    )}
                  </div>
                </div>
              );
            })
          )}
        </div>

        {/* Footer */}
        <div className="px-5 py-3 border-t border-slate-200 bg-slate-50 flex items-center justify-between">
          <button
            onClick={copyPracticeSheet}
            disabled={isLoading || practiceItems.length === 0}
            className="inline-flex items-center text-xs font-semibold px-3 py-1.5 rounded-lg border border-slate-200 bg-white text-slate-700 hover:bg-slate-50 shadow-2xs"
          >
            {copied ? (
              <>
                <Check className="w-3.5 h-3.5 mr-1 text-emerald-600" /> Copied Practice
              </>
            ) : (
              <>
                <Copy className="w-3.5 h-3.5 mr-1 text-slate-500" /> Copy to Clipboard
              </>
            )}
          </button>

          <button
            onClick={onClose}
            className="px-4 py-1.5 text-xs font-semibold bg-slate-900 text-white rounded-lg hover:bg-slate-800"
          >
            Done
          </button>
        </div>
      </div>
    </div>
  );
};
